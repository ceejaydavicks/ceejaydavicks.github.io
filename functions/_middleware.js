/* Adds baseline security headers to every response (static pages + API),
   turns uncaught Function errors into readable JSON for /api/* requests, and
   owns the cache policy for HTML and JS/CSS.

   Why caching lives here: Cloudflare Pages does NOT apply `_headers` rules to
   responses generated by Pages Functions. Every HTML page on this site passes
   through this middleware, so this is the only place that can reliably say
   "revalidate HTML on every request" and "cache versioned assets forever".

   Why asset URLs are rewritten here: Cloudflare exposes the deployment's
   commit SHA as an environment variable, so the version can be injected into
   the HTML at the edge instead of being hand-edited into every HTML file on
   every deploy. A new deploy therefore always ships new asset URLs.          */

import { injectWatchMeta, watchMeta } from "./_lib/watch-meta.js";
import {
  deployVersion,
  versionHtml,
  htmlEtag,
  isVersionedAsset,
  HTML_CACHE_CONTROL,
  VERSIONED_CACHE_CONTROL
} from "./_lib/asset-version.js";

const MAX_DETAIL = 300;

function cleanDetail(value) {
  return String(value == null ? "" : value)
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, MAX_DETAIL);
}

/* Configuration problems name a binding or a secret — never its value — so they
   are safe to show, and are reported as 503 ("not set up yet") rather than 500. */
function isConfigurationError(detail) {
  return /missing d1 binding|r2 bucket is not configured|admin_password|session_secret|telegram bot is not configured|no telegram admins|not configured/i.test(
    detail
  );
}

function errorResponse(request, error) {
  const path = new URL(request.url).pathname;
  const detail = cleanDetail(error && error.message ? error.message : error) || "Unknown error";
  const configuration = isConfigurationError(detail);

  if (!path.startsWith("/api/")) {
    return new Response(configuration ? detail : "Internal Server Error", {
      status: configuration ? 503 : 500,
      headers: { "content-type": "text/plain; charset=utf-8", "cache-control": "no-store" }
    });
  }

  return new Response(
    JSON.stringify({
      error: configuration ? detail : "Server error",
      detail,
      code: configuration ? "configuration_error" : "server_error",
      hint: "Open /api/health on this site to see which binding or secret is missing."
    }),
    {
      status: configuration ? 503 : 500,
      headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store" }
    }
  );
}

function securityHeaders(headers, path) {
  headers.set("x-content-type-options", "nosniff");
  headers.set("referrer-policy", "strict-origin-when-cross-origin");
  headers.set("x-frame-options", "SAMEORIGIN");
  headers.set("permissions-policy", "geolocation=(), microphone=(), camera=(), payment=()");

  // The admin page is noindex in its own <meta> too; this covers the headers.
  if (path === "/admin" || path.startsWith("/admin/")) {
    headers.set("x-robots-tag", "noindex, nofollow, noarchive");
  }
  if (path.startsWith("/api/")) {
    headers.set("x-robots-tag", "noindex");
  }
}

function passThrough(response, headers) {
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers
  });
}

export async function onRequest(context) {
  const url = new URL(context.request.url);
  const path = url.pathname;

  let response;
  try {
    response = await context.next();
  } catch (error) {
    response = errorResponse(context.request, error);
  }

  if (response.status === 204) return response;

  const headers = new Headers(response.headers);
  securityHeaders(headers, path);

  /* The watch URL must always be a page, never a download. The dedicated
     watch Function also removes this header; this is the belt-and-braces
     path for deployments where only the middleware matches /watch/. */
  const isWatch = path === "/watch" || path.startsWith("/watch/");
  if (isWatch) headers.delete("content-disposition");

  const isScriptOrStyle = /\.(?:js|mjs|css)$/i.test(path);

  /* A 304 carries no body, but it must still repeat the same cache policy. */
  if (response.status === 304) {
    if (isScriptOrStyle) {
      headers.set(
        "cache-control",
        isVersionedAsset(url) ? VERSIONED_CACHE_CONTROL : HTML_CACHE_CONTROL
      );
    } else if (!path.startsWith("/api/")) {
      headers.set("cache-control", HTML_CACHE_CONTROL);
    }
    return new Response(null, { status: 304, headers });
  }

  /* JS/CSS: versioned URLs are immutable, anything else revalidates. The
     static file itself is untouched — only the Cache-Control header changes. */
  if (isScriptOrStyle) {
    headers.set(
      "cache-control",
      isVersionedAsset(url) ? VERSIONED_CACHE_CONTROL : HTML_CACHE_CONTROL
    );
    return passThrough(response, headers);
  }

  if (!String(headers.get("content-type") || "").includes("text/html")) {
    return passThrough(response, headers);
  }

  /* HTML: revalidate on every request, and ship asset URLs that are unique to
     this deployment. Keeping the HTML uncached is what makes a new deploy
     visible immediately; the version query is what makes the new assets load. */
  let html;
  try {
    html = await response.clone().text();

    if (isWatch && response.status === 200) {
      /* If the dedicated watch Function did not run (route matching differs
         between Pages projects), inject the social preview tags here as a
         fallback. injectWatchMeta is idempotent, so running it in both places
         is harmless. */
      const id = String(url.searchParams.get("v") || "").trim();
      if (id && !/<meta\s+property="og:url"/i.test(html)) {
        const meta = await watchMeta(context.env, url.origin, id);
        html = injectWatchMeta(html, meta);
      }
    }
  } catch (error) {
    return passThrough(response, headers);
  }

  const version = await deployVersion(context.env, url.origin);
  const body = versionHtml(html, version);

  headers.set("content-type", "text/html; charset=utf-8");
  headers.set("cache-control", HTML_CACHE_CONTROL);
  headers.delete("content-length");
  headers.delete("content-encoding");
  headers.delete("etag");
  headers.delete("content-disposition");

  const etag = htmlEtag(body);
  headers.set("etag", etag);
  if (context.request.headers.get("if-none-match") === etag) {
    return new Response(null, { status: 304, headers });
  }

  return new Response(body, {
    status: response.status,
    statusText: response.statusText,
    headers
  });
}
